import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { Poet } from '../src/types/poet';
import { poets as canonicalPoets } from '../src/data/library/index';

/**
 * One canonical author record, two delivery shapes:
 *   - small synchronous card/search payload for the existing app shell;
 *   - full static JSON fetched only when visiting an extended author page.
 * Never duplicate authored biographies, editing is done only in src/data/library.
 */
/**
 * Materialize/check canonical poet data projections without mutating build
 * artifacts on validation. Used by Vite and the existing authoring validator.
 */
export function materializeSupplementaryPoets(check: boolean): void {
const ids = [
  'marina-tsvetaeva',
  'osip-mandelstam',
  'valery-bryusov',
  'nikolay-nekrasov',
  'konstantin-simonov',
  'aleksey-konstantinovich-tolstoy',
] as const;
const root = process.cwd();

const selected = ids.map((id) => {
  const matches = canonicalPoets.filter((poet) => poet.id === id);
  if (matches.length !== 1) throw new Error('Author authority not unique: ' + id);
  return matches[0];
});
function sha(bytes: string) {
  return crypto.createHash('sha256').update(bytes).digest('hex');
}
function assertOrWrite(filename: string, content: string) {
  const target = path.join(root, filename);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n?/g, '\n') !== content) {
      throw new Error('Supplementary author generated artifact is stale: ' + filename);
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, 'utf8');
  }
}
const stubs: Poet[] = selected.map((poet) => ({
  ...poet,
  fullBio: poet.shortBio,
  historicalNote: undefined,
  spiritualSearch: undefined,
  moralPortrait: undefined,
  authorCommentary: undefined,
  sources: undefined,
  testimonies: undefined,
}));
const materialized = selected.map((poet) => [poet.id, JSON.stringify(poet) + '\n'] as const);
const revision = sha(materialized.map((item) => item[1]).join('')).slice(0, 16);
const ts = [
  "import type { Poet } from '../../types/poet';",
  '/** Auto-generated from six canonical author modules. Do not edit this file manually. */',
  'export const supplementaryCatalogRevision = ' + JSON.stringify(revision) + ';',
  'export const supplementaryPoetIds: readonly string[] = ' + JSON.stringify([...ids]) + ';',
  'export const supplementaryPoets: Poet[] = ' + JSON.stringify(stubs, null, 2) + ';',
  'export async function loadSupplementaryPoet(id: string, signal: AbortSignal): Promise<Poet> {',
  '  if (!supplementaryPoetIds.includes(id)) throw new Error("Unknown supplemental author");',
  '  const uri = (import.meta.env.BASE_URL || "/") + "data/poets/" + id + ".json?v=" + supplementaryCatalogRevision;',
  '  const response = await fetch(uri, { signal, credentials: "same-origin" });',
  '  if (!response.ok) throw new Error("Author data unavailable: " + response.status);',
  '  const value = await response.json() as Poet;',
  '  if (value.id !== id || typeof value.fullBio !== "string" || value.fullBio.length < 200 || !Array.isArray(value.poems)) throw new Error("Invalid author data");',
  '  return value;',
  '}',

  '',
].join('\n');
assertOrWrite('src/data/runtime/supplementaryPoets.generated.ts', ts);
for (const [id, json] of materialized) {
  assertOrWrite('public/data/poets/' + id + '.json', json);
}
// Derive the small runtime registry from the canonical source ordering.
// The duplicated manual index would drift when an author is edited or added.
const registrySource = fs.readFileSync(path.join(root, 'src/data/library/index.ts'), 'utf8');
const registrySourceImports = new Map(
  [...registrySource.matchAll(/^import \{ (\w+) \} from '\.\/(\w+)';$/gm)]
    .map((match) => [match[1], match[2]] as const),
);
const canonicalArrayMatch = registrySource.match(/export const poets: Poet\[\] = \[([\s\S]*?)\];/);
if (!canonicalArrayMatch) throw new Error('Canonical author array could not be parsed');
const canonicalBindings = canonicalArrayMatch[1].split(',').map((value) => value.trim()).filter(Boolean);
if (canonicalBindings.length !== canonicalPoets.length
    || new Set(canonicalBindings).size !== canonicalBindings.length
    || new Set(canonicalPoets.map((poet) => poet.id)).size !== canonicalPoets.length) {
  throw new Error('Canonical author registry bindings are not one-to-one');
}
const selectedIds = new Set<string>(ids);
const imports: string[] = [];
const bindings: string[] = [];
for (let index = 0; index < canonicalBindings.length; index += 1) {
  const variable = canonicalBindings[index];
  const author = canonicalPoets[index];
  const moduleName = registrySourceImports.get(variable);
  if (!moduleName) throw new Error('Missing canonical import for author: ' + variable);
  if (selectedIds.has(author.id)) {
    const supplementIndex = ids.indexOf(author.id as (typeof ids)[number]);
    if (supplementIndex < 0) throw new Error('Unknown supplemental author: ' + author.id);
    bindings.push('supplementaryPoets[' + supplementIndex + ']');
  } else {
    imports.push("import { " + variable + " } from '../library/" + moduleName + "';");
    bindings.push(variable);
  }
}
const runtimeTs = [
  "import type { Poet } from '../../types/poet';",
  '/** Generated from library/index.ts: canonical author order, light data for the web app. */',
  ...imports,
  "import { supplementaryPoets } from './supplementaryPoets.generated';",
  '',
  'export const poets: Poet[] = [',
  ...bindings.map((binding) => '  ' + binding + ','),
  '];',
  '',
].join('\n');
assertOrWrite('src/data/runtime/poetRuntimeIndex.generated.ts', runtimeTs);

console.log('Supplementary poet data ' + (check ? 'verified' : 'materialized') + ': ' + selected.length + ' poets; revision=' + revision);
}
