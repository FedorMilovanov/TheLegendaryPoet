import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { memoryPlaces } from '../src/data/memory-places';

export function materializeMemoryPlaces(check: boolean) {
  const folder = resolve('public/data/memory-places');
  const indexPath = resolve('src/data/runtime/memoryPlaces.generated.ts');
  const groups = new Map<string, typeof memoryPlaces>();
  for (const place of memoryPlaces) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(place.poetId)) throw new Error('Invalid poet id');
    groups.set(place.poetId, [...(groups.get(place.poetId) ?? []), place]);
  }
  const revisions: Record<string, string> = {};
  const expected = new Map<string, string>();
  for (const [id, places] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const content = JSON.stringify(places) + '\n';
    revisions[id] = createHash('sha256').update(content).digest('hex').slice(0, 16);
    expected.set(resolve(folder, id + '.json'), content);
  }
  expected.set(indexPath, '// Generated by scripts/gen-memory-places.ts. Do not edit.\nexport const memoryPlaceRevisions: Readonly<Record<string, string>> = ' + JSON.stringify(revisions, null, 2) + ';\n');
  const existing = existsSync(folder) ? readdirSync(folder) : [];
  for (const name of existing) {
    if (!expected.has(resolve(folder, name))) throw new Error('Unexpected memory place artifact: ' + name);
  }
  for (const [path, content] of expected) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === content) continue;
    if (check) throw new Error('Stale memory place artifact: ' + path + '; run npm run memory:generate');
    mkdirSync(folder, { recursive: true });
    writeFileSync(path, content, 'utf8');
  }
  console.log('Memory place artifacts:', groups.size, 'poet-scoped payloads', check ? 'verified' : 'generated');
}
