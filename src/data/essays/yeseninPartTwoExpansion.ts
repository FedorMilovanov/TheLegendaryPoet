export function expandYeseninPartTwoBlocks(blocks: readonly EssayBlock[]): EssayBlock[] {
  const expanded: EssayBlock[] = [];
  for (const block of blocks) {
    expanded.push(block);
    if (block.type !== 'section') continue;

    const additions = expansionBySection[block.heading] ?? [];
    const visualKeys = visualKeysBySection[block.heading] ?? [];
    if (additions.length === 0 && visualKeys.length === 0) continue;

    // Place one documentary visual after the first added paragraph when possible;
    // any additional visuals follow the textual expansion for the same canonical section.
    if (additions.length > 0) {
      expanded.push(additions[0]);
      if (visualKeys[0]) expanded.push(visualBlocks[visualKeys[0]]);
      expanded.push(...additions.slice(1));
      for (const key of visualKeys.slice(1)) expanded.push(visualBlocks[key]);
    } else {
      for (const key of visualKeys) expanded.push(visualBlocks[key]);
    }
  }
  return expanded;
}
