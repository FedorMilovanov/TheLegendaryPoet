export function supplementYeseninPartTwoBlocks(blocks: readonly EssayBlock[]): EssayBlock[] {
  const supplemented: EssayBlock[] = [];
  for (const block of blocks) {
    supplemented.push(block);
    if (block.type !== 'section') continue;
    supplemented.push(...(supplementBySection[block.heading] ?? []));
  }
  return supplemented;
}
